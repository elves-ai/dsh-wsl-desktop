import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');

test('offline speech initialization and cancellation are restricted to trusted settings views', () => {
  const names = ['initialize_speech_environment', 'cancel_speech_initialization'];
  const cap = JSON.parse(read('src-tauri/capabilities/speech-settings.json'));
  assert.equal(cap.local, true);
  assert.equal(cap.remote, undefined);
  assert.deepEqual(cap.webviews, ['launcher-settings', 'dsh-settings']);
  for (const name of names) {
    const permission = 'allow-' + name.replaceAll('_', '-');
    assert.ok(cap.permissions.includes(permission));
    assert.ok(read('src-tauri/build.rs').includes('"' + name + '"'));
    assert.ok(read('src-tauri/src/desktop.rs').includes('speech_settings::' + name));
    assert.ok(read('src-tauri/permissions/autogenerated/' + name + '.toml').includes('commands.allow = ["' + name + '"]'));
    for (const file of readdirSync(new URL('../src-tauri/capabilities/', import.meta.url)).filter(n => n.endsWith('.json') && n !== 'speech-settings.json')) {
      assert.ok(!JSON.parse(read('src-tauri/capabilities/' + file)).permissions.includes(permission), file + ' must not initialize environments');
    }
  }
  const native = read('src-tauri/src/desktop_speech_settings.rs');
  const initialize = native.slice(native.indexOf('async fn initialize_speech_environment'), native.indexOf('fn cancel_speech_initialization'));
  assert.match(initialize, /assert_page\(&view, true\)\?/);
  assert.match(initialize, /spawn_blocking/);
  assert.match(initialize, /resources\.initialize\(config, &speech\)/);
  const cancel = native.slice(native.indexOf('fn cancel_speech_initialization'), native.indexOf('async fn discover_speech_resources'));
  assert.match(cancel, /assert_page\(&view, false\)\?/);
  assert.match(cancel, /cancel_initialization\(\)/);
  const wsl = read('src-tauri/src/speech_wsl.rs');
  assert.ok(wsl.includes('"--resources-initialize"'));
  assert.match(wsl.slice(wsl.indexOf('fn initialize('), wsl.indexOf('fn discover(', wsl.indexOf('fn initialize('))), /true,\s*cancel,/);
});
